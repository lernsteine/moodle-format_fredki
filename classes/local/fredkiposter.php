namespace format_fredki\local;

/**
 * FredKI's own contributions to the group: answers to posts and the question of the day.
 *
 * Everything FredKI writes is created on the server from FredKI's answer. Browsers never send
 * text that is then published under FredKI's name.
 *
 * @package    format_fredki
 * @copyright  2026 lernsteine.com
 * @license    https://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class fredkiposter {
    /**
     * FredKI answers a post in its conversation, once.
     *
     * @param int $postid Post id.
     * @param string $mode "mention" (asked directly) or "answer" (open question).
     * @return array|null ['postid' => int, 'text' => string] or null if nothing was posted.
     */
    public static function answer_post(int $postid, string $mode): ?array {
        global $DB;
        $post = $DB->get_record('forum_posts', ['id' => $postid, 'deleted' => 0]);
        if (!$post || botuser::is_bot((int)$post->userid)) {
            return null;
        }
        $meta = community::get_meta([$postid]);
        if (!empty($meta[$postid]->fredkianswered)) {
            return null;
        }
        $discussion = $DB->get_record('forum_discussions', ['id' => $post->discussion], '*', MUST_EXIST);
        $course = get_course($discussion->course);
        if ($course->format !== 'fredki' || fredki::get_source($course) === '') {
            return null;
        }
        $community = community::require_forum_record($course);
        if ((int)$community['forum']->id !== (int)$discussion->forum) {
            return null;
        }
        // Mark first, so a second trigger (browser and background task) does not answer twice.
        community::set_meta($postid, null, true);
        try {
            $question = community::plain($post->message, (int)$post->messageformat);
            $question = trim(preg_replace('/@fredki\b/iu', '', $question));
            $prompt = fredki::build_message($mode, $course, 0, $question, (int)$discussion->id);
            $answer = fredki::complete($course, $prompt);
            $replyid = community::post_fredki_reply($course, (int)$discussion->id, $answer, $postid);
        } catch (\Throwable $e) {
            community::set_meta($postid, null, false);
            throw $e;
        }
        return ['postid' => $replyid, 'text' => $answer];
    }

    /**
     * FredKI posts a reply that a learner received privately and decided to share publicly.
     *
     * @param \stdClass $course Course.
     * @param int $discussionid Conversation.
     * @param string $answer Answer generated by FredKI on the server.
     * @return int Post id.
     */
    public static function share_answer(\stdClass $course, int $discussionid, string $answer): int {
        return community::post_fredki_reply($course, $discussionid, $answer);
    }

    /** Longest question of the day that is used, in characters. */
    const QUESTION_MAX = 160;

    /** Number of fallback questions in the language files. */
    const FALLBACK_COUNT = 6;

    /**
     * Find one short question in FredKI's answer.
     *
     * Markdown, headings, emojis and quotes are removed. If the answer holds several questions,
     * the shortest one wins. Text without a short question gives an empty string.
     *
     * @param string $answer Answer of FredKI.
     * @return string
     */
    public static function extract_question(string $answer): string {
        $text = html_entity_decode(strip_tags($answer), ENT_QUOTES | ENT_HTML5, 'UTF-8');
        // Markdown: headings, emphasis, list markers, links, code.
        $text = preg_replace('/^\s{0,3}(#{1,6}|[-*+>]|\d+[.)])\s+/mu', '', $text);
        $text = preg_replace('/\[([^\]]*)\]\([^)]*\)/u', '$1', $text);
        $text = str_replace(['***', '**', '__', chr(96)], '', $text);
        $text = preg_replace('/(?<!\w)[*_](?=\S)|(?<=\S)[*_](?!\w)/u', '', $text);
        // Emojis and other pictographs.
        $text = preg_replace('/[\x{1F000}-\x{1FAFF}\x{2600}-\x{27BF}\x{FE0F}\x{200D}]/u', '', $text);
        $text = trim(preg_replace('/\s+/u', ' ', $text));
        if ($text === '') {
            return '';
        }
        $clean = static function (string $q): string {
            $q = trim($q, " \t\n\r\0\x0B\"„“”'‚‘’«»:–—-");
            return preg_replace('/^(question|frage)( of the day| des tages)?\s*:\s*/iu', '', $q);
        };
        $whole = $clean($text);
        if (\core_text::strlen($whole) <= self::QUESTION_MAX && preg_match('/\?$/u', $whole)) {
            return $whole;
        }
        // Several sentences: take the shortest real question.
        preg_match_all('/[^.!?]*\?/u', $text, $matches);
        $best = '';
        foreach ($matches[0] as $candidate) {
            $candidate = $clean($candidate);
            $length = \core_text::strlen($candidate);
            if ($length < 12 || $length > self::QUESTION_MAX || count(preg_split('/\s+/u', $candidate)) < 3) {
                continue;
            }
            if ($best === '' || $length < \core_text::strlen($best)) {
                $best = $candidate;
            }
        }
        return $best;
    }

    /**
     * A calm open question, for days when FredKI's answer holds no short question.
     *
     * @return string
     */
    public static function fallback_question(): string {
        $index = ((int)floor(time() / DAYSECS) % self::FALLBACK_COUNT) + 1;
        return get_string('fallbackquestion' . $index, 'format_fredki');
    }

    /**
     * FredKI's question of the day: asked once per day as a real conversation of the group.
     *
     * @param \stdClass $course Course.
     * @param string $question Question generated by FredKI.
     * @return int Discussion id, 0 if a question exists already.
     */
    public static function post_daily_question(\stdClass $course, string $question): int {
        $lock = \core\lock\lock_config::get_lock_factory('format_fredki')
            ->get_lock('dailyquestion_' . $course->id, 10);
        if (!$lock) {
            return 0;
        }
        try {
            $community = community::require_forum_record($course);
            if (community::get_today_question($community)) {
                return 0;
            }
            return community::post_fredki_discussion($course, $question, 'question');
        } finally {
            $lock->release();
        }
    }
}
